import { AgentExecutionContext, AgentExecutionResult, PlanStep, GeneratedArtifact } from '../../core/types';

/**
 * Transformation Scaffolder Agent
 *
 * Generates dbt project scaffolding including models, tests, macros,
 * and YAML configuration files based on the target environment.
 */
export async function executeTransformScaffoldAgent(
  step: PlanStep,
  context: AgentExecutionContext
): Promise<AgentExecutionResult> {
  const target = context.targetEnvironment;
  const pc = target?.platformConfig as unknown as Record<string, string> | undefined;
  const targetDb = pc?.['database'] || 'CURATED_DB';
  const targetSchema = pc?.['schema'] || 'ANALYTICS';
  const namingConvention = target?.namingConvention || 'snake_case';

  context.log(`Transformation Scaffolder generating dbt project for ${targetDb}.${targetSchema}...`);

  const projectName = `${targetDb.toLowerCase()}_${targetSchema.toLowerCase()}`;
  const artifacts: GeneratedArtifact[] = [];

  // 1. dbt_project.yml
  const dbtProjectYml = generateDbtProjectYml(projectName, targetDb, targetSchema);
  artifacts.push(createArtifact(step, 'dbt_project.yml', dbtProjectYml, 'yaml', 'dbt project configuration'));

  // 2. Model SQL files
  const stagingModel = generateStagingModel(targetDb, targetSchema, namingConvention);
  artifacts.push(createArtifact(step, `models/staging/${applyNaming('stg_sales', namingConvention)}.sql`, stagingModel, 'sql', 'staging model'));

  const intermediateModel = generateIntermediateModel(targetDb, targetSchema, namingConvention);
  artifacts.push(createArtifact(step, `models/intermediate/${applyNaming('int_sales_aggregated', namingConvention)}.sql`, intermediateModel, 'sql', 'intermediate model'));

  const martsModel = generateMartsModel(targetDb, targetSchema, namingConvention);
  artifacts.push(createArtifact(step, `models/marts/${applyNaming('fct_sales', namingConvention)}.sql`, martsModel, 'sql', 'marts model'));

  // 3. Schema YML with tests
  const schemaYml = generateSchemaYml(targetDb, targetSchema, namingConvention);
  artifacts.push(createArtifact(step, `models/marts/${applyNaming('schema', namingConvention)}.yml`, schemaYml, 'yaml', 'schema tests'));

  // 4. Generic tests
  const genericTests = generateGenericTests(targetDb, targetSchema, namingConvention);
  artifacts.push(createArtifact(step, 'tests/generic/assert_positive_amounts.sql', genericTests, 'sql', 'generic test'));

  // 5. Macros
  const macros = generateMacros(namingConvention);
  artifacts.push(createArtifact(step, `macros/${applyNaming('generate_schema_name', namingConvention)}.sql`, macros, 'sql', 'custom macro'));

  // Register all artifacts
  for (const artifact of artifacts) {
    if (context.addArtifact) {
      context.addArtifact(artifact);
    }
  }

  return {
    success: true,
    message: `Transformation Scaffolder generated dbt project "${projectName}" with ${artifacts.length} files.`,
    details: {
      projectName,
      targetDb,
      targetSchema,
      fileCount: artifacts.length,
      files: artifacts.map((a) => a.title)
    },
    artifacts
  };
}

// ── Generators ──

function generateDbtProjectYml(projectName: string, db: string, schema: string): string {
  return `# dbt Project Configuration
# Generated by AutoDE Transformation Scaffolder

name: '${projectName}'
version: '1.0.0'
config-version: 2

profile: '${projectName}'

model-paths: ["models"]
analysis-paths: ["analyses"]
test-paths: ["tests"]
seed-paths: ["seeds"]
macro-paths: ["macros"]
snapshot-paths: ["snapshots"]

target-path: "target"
clean-targets:
  - "target"
  - "dbt_packages"

models:
  ${projectName}:
    staging:
      +materialized: view
      +schema: ${schema}_staging
      +database: ${db}
    intermediate:
      +materialized: ephemeral
      +schema: ${schema}_intermediate
    marts:
      +materialized: table
      +schema: ${schema}
      +database: ${db}

seeds:
  ${projectName}:
    +schema: ${schema}_seeds

snapshots:
  ${projectName}:
    +schema: ${schema}_snapshots
`;
}

function generateStagingModel(db: string, schema: string, naming: string): string {
  const tableName = applyNaming('stg_sales', naming);
  return `-- Staging model: raw → cleaned
-- Source: ${db}.${schema}.raw_sales

WITH source AS (
    SELECT * FROM {{ source('${schema}', 'raw_sales') }}
),

renamed AS (
    SELECT
        ${applyNaming('transaction_id', naming)}::STRING AS ${applyNaming('transaction_id', naming)},
        ${applyNaming('customer_id', naming)}::STRING AS ${applyNaming('customer_id', naming)},
        ${applyNaming('product_id', naming)}::STRING AS ${applyNaming('product_id', naming)},
        ${applyNaming('quantity', naming)}::INTEGER AS ${applyNaming('quantity', naming)},
        ${applyNaming('unit_price', naming)}::DECIMAL(10,2) AS ${applyNaming('unit_price', naming)},
        ${applyNaming('transaction_date', naming)}::DATE AS ${applyNaming('transaction_date', naming)},
        CURRENT_TIMESTAMP() AS ${applyNaming('dbt_loaded_at', naming)}
    FROM source
    WHERE ${applyNaming('transaction_id', naming)} IS NOT NULL
)

SELECT * FROM renamed
`;
}

function generateIntermediateModel(db: string, schema: string, naming: string): string {
  const tableName = applyNaming('int_sales_aggregated', naming);
  return `-- Intermediate model: daily aggregations
-- Builds on: stg_sales

WITH daily_sales AS (
    SELECT
        ${applyNaming('customer_id', naming)},
        ${applyNaming('product_id', naming)},
        ${applyNaming('transaction_date', naming)},
        SUM(${applyNaming('quantity', naming)}) AS ${applyNaming('total_quantity', naming)},
        SUM(${applyNaming('quantity', naming)} * ${applyNaming('unit_price', naming)}) AS ${applyNaming('total_revenue', naming)},
        COUNT(DISTINCT ${applyNaming('transaction_id', naming)}) AS ${applyNaming('transaction_count', naming)}
    FROM {{ ref('${applyNaming('stg_sales', naming)}') }}
    GROUP BY 1, 2, 3
)

SELECT * FROM daily_sales
`;
}

function generateMartsModel(db: string, schema: string, naming: string): string {
  const tableName = applyNaming('fct_sales', naming);
  return `-- Marts model: fact table with dimensions
-- Builds on: int_sales_aggregated, dim_customer, dim_product, dim_date

SELECT
    {{ dbt_utils.generate_surrogate_key(['s.${applyNaming('customer_id', naming)}', 's.${applyNaming('product_id', naming)}', 's.${applyNaming('transaction_date', naming)}']) }} AS ${applyNaming('sales_key', naming)},
    c.${applyNaming('customer_key', naming)},
    p.${applyNaming('product_key', naming)},
    d.${applyNaming('date_key', naming)},
    s.${applyNaming('total_quantity', naming)},
    s.${applyNaming('total_revenue', naming)},
    s.${applyNaming('transaction_count', naming)},
    s.${applyNaming('transaction_date', naming)},
    CURRENT_TIMESTAMP() AS ${applyNaming('dbt_updated_at', naming)}
FROM {{ ref('${applyNaming('int_sales_aggregated', naming)}') }} s
LEFT JOIN {{ ref('${applyNaming('dim_customer', naming)}') }} c
    ON s.${applyNaming('customer_id', naming)} = c.${applyNaming('customer_id', naming)}
LEFT JOIN {{ ref('${applyNaming('dim_product', naming)}') }} p
    ON s.${applyNaming('product_id', naming)} = p.${applyNaming('product_id', naming)}
LEFT JOIN {{ ref('${applyNaming('dim_date', naming)}') }} d
    ON s.${applyNaming('transaction_date', naming)} = d.${applyNaming('full_date', naming)}
`;
}

function generateSchemaYml(db: string, schema: string, naming: string): string {
  return `version: 2

models:
  - name: ${applyNaming('fct_sales', naming)}
    description: "Fact table containing daily aggregated sales metrics"
    columns:
      - name: ${applyNaming('sales_key', naming)}
        description: "Surrogate key for the sales fact"
        tests:
          - unique
          - not_null
      - name: ${applyNaming('customer_key', naming)}
        description: "Foreign key to dim_customer"
        tests:
          - not_null
          - relationships:
              to: ref('${applyNaming('dim_customer', naming)}')
              field: ${applyNaming('customer_key', naming)}
      - name: ${applyNaming('product_key', naming)}
        description: "Foreign key to dim_product"
        tests:
          - not_null
          - relationships:
              to: ref('${applyNaming('dim_product', naming)}')
              field: ${applyNaming('product_key', naming)}
      - name: ${applyNaming('date_key', naming)}
        description: "Foreign key to dim_date"
        tests:
          - not_null
          - relationships:
              to: ref('${applyNaming('dim_date', naming)}')
              field: ${applyNaming('date_key', naming)}
      - name: ${applyNaming('total_quantity', naming)}
        description: "Total quantity sold per day"
        tests:
          - not_null
          - dbt_utils.expression_is_true:
              expression: ">= 0"
      - name: ${applyNaming('total_revenue', naming)}
        description: "Total revenue per day"
        tests:
          - not_null
          - dbt_utils.expression_is_true:
              expression: ">= 0"
      - name: ${applyNaming('transaction_count', naming)}
        description: "Number of distinct transactions per day"
        tests:
          - not_null
          - dbt_utils.expression_is_true:
              expression: ">= 0"
`;
}

function generateGenericTests(db: string, schema: string, naming: string): string {
  return `-- Generic test: Assert all amounts are positive
-- Applies to: fct_sales

{% test ${applyNaming('assert_positive_amounts', naming)}(model, column_name) %}

SELECT
    ${applyNaming('transaction_date', naming)},
    SUM(CASE WHEN {{ column_name }} < 0 THEN 1 ELSE 0 END) AS ${applyNaming('negative_count', naming)}
FROM {{ model }}
GROUP BY 1
HAVING SUM(CASE WHEN {{ column_name }} < 0 THEN 1 ELSE 0 END) > 0

{% endtest %}
`;
}

function generateMacros(naming: string): string {
  return `-- Custom macro: generate schema name with environment prefix
-- Overrides dbt's default schema generation

{% macro ${applyNaming('generate_schema_name', naming)}(custom_schema_name, node) -%}

    {%- set default_schema = target.schema -%}
    {%- if custom_schema_name is none -%}
        {{ default_schema }}
    {%- else -%}
        {{ custom_schema_name | trim }}
    {%- endif -%}

{%- endmacro %}
`;
}

// ── Helpers ──

function createArtifact(step: PlanStep, filePath: string, content: string, language: 'sql' | 'yaml' | 'markdown' | 'python' | 'json', description: string): GeneratedArtifact {
  const fileName = filePath.split('/').pop() || filePath;
  return {
    id: `scaffold-${step.id}-${fileName.replace(/[^a-zA-Z0-9_]/g, '_')}-${Date.now()}`,
    type: 'sql_script',
    title: fileName,
    description,
    content,
    language,
    generatedBy: 'transformScaffoldAgent',
    generatedAt: new Date().toISOString(),
    approved: false,
    filePath
  };
}

function applyNaming(name: string, convention: string): string {
  switch (convention) {
    case 'camelCase':
      return name.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
    case 'PascalCase':
      return name.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());
    case 'snake_case':
    default:
      return name;
  }
}